"""Add a private DJANGO_SECRET_KEY to .env if it does not have one yet (used by setup.bat / setup.sh)."""
import secrets
import sys
from pathlib import Path

env = Path(__file__).resolve().parent.parent / ".env"
text = env.read_text(encoding="utf-8") if env.exists() else ""
if any(line.startswith("DJANGO_SECRET_KEY=") for line in text.splitlines()):
    sys.exit(0)
with env.open("a", encoding="utf-8") as f:
    f.write("\n# Private key for this installation (generated by setup). Keep it secret; do not change it.\n")
    f.write(f"DJANGO_SECRET_KEY={secrets.token_urlsafe(50)}\n")
print("Generated a private DJANGO_SECRET_KEY in .env.")
